const server = http.createServer(async (req, res) => {
  res.setHeader('Access-Control-Allow-Origin', '*')
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type, Authorization, X-DailyWorkMate-Model-Selection')
  if (req.method === 'OPTIONS') { res.writeHead(204).end(); return }
  if (req.url === '/v1/models') { discoveryRequests++; res.setHeader('Content-Type', 'application/json'); res.end(JSON.stringify({ data: [{ id: 'qa-model' }, { id: 'qa-model-alt' }, ...(!omitBadModel ? [{ id: 'qa-model-bad' }] : [])] })); return }
  if (req.url === '/qa-avatar') { res.end('data:model/gltf-binary;base64,' + fs.readFileSync(path.join(root, 'src/renderer/src/assets/companion/pink-ai-octopus.glb')).toString('base64')); return }
  let raw = ''
  req.setEncoding('utf8')
  for await (const bytes of req) raw += bytes
  const body = JSON.parse(raw)
  if (req.url === '/v1/models/verify') { verificationRequests++; res.setHeader('Content-Type', 'application/json'); res.end(JSON.stringify({ model: body.model === 'qa-model-bad' ? 'qa-model-alt' : body.model, verified: false, skipped: true, recovered: body.model === 'qa-model-bad', providerName: 'QA' })); return }
  requests.push(body)
  assert.equal(req.headers['x-dailyworkmate-model-selection'], 'explicit')
  // Chat-only turns: the workspace hand-off tool, and a model that rejects tools.
  const lastUser = String(body.messages.at(-1)?.content || '')
  const handoffTool = (body.tools || []).some(tool => tool.function?.name === 'use_workspace_agent')
  if (handoffTool && lastUser.includes('NOTOOLS')) { res.writeHead(400, { 'Content-Type': 'application/json' }); res.end(JSON.stringify({ error: { message: 'This model does not support tools' } })); return }
  if (handoffTool && lastUser.includes('HANDOFF')) {
    res.setHeader('Content-Type', 'text/event-stream')
    const chunk = value => res.write('data: ' + JSON.stringify(value) + '\n\n')
    chunk({ choices: [{ delta: { content: 'Let me check. ', tool_calls: [{ index: 0, id: 'handoff', type: 'function', function: { name: 'use_workspace_agent', arguments: '' } }] } }] })
    chunk({ choices: [{ delta: { tool_calls: [{ index: 0, function: { arguments: '{"reason":"read files"}' } }] }, finish_reason: 'tool_calls' }] })
    res.end('data: [DONE]\n\n'); return
  }
  res.setHeader('Content-Type', 'text/event-stream')
  const send = content => res.write('data: ' + JSON.stringify({ choices: [{ delta: { content } }] }) + '\n\n')
  if (body.messages[0]?.content.startsWith('Summarize the supplied assistant reply')) {
    if (body.messages.at(-1)?.content.includes('SUMMARYWAITQA')) {
      pendingSummaryRequests++
      res.flushHeaders()
      res.once('close', () => { pendingSummaryRequests--; cancelledSummaryRequests++ })
      return
    }
    send('口播摘要完成。'); res.end('data: [DONE]\n\n'); return
  }
  if (body.messages.at(-1)?.content === 'VOICE_LONG_QA') { send(longReply); res.end('data: [DONE]\n\n'); return }
  send('Hello from your companion. ')
  if (JSON.stringify(body.messages).includes('WAIT_QA')) {
    const timer = setTimeout(() => res.end('data: [DONE]\n\n'), 5000)
    res.on('close', () => clearTimeout(timer))
  } else { send('CHAT_QA_COMPLETE'); res.end('data: [DONE]\n\n') }
})
